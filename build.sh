#!/usr/bin/env bash
# Builds WatchMatch.apk without Gradle: aapt2, javac, d8, zipalign, apksigner.
set -euo pipefail
cd "$(dirname "$0")"

die() { echo "Error: $*" >&2; exit 1; }

# --- Android SDK and JDK ---------------------------------------------------
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
  for d in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" \
           /opt/homebrew/share/android-commandlinetools \
           /usr/local/share/android-commandlinetools /usr/lib/android-sdk; do
    if [ -d "$d/build-tools" ]; then SDK="$d"; break; fi
  done
fi
[ -n "$SDK" ] && [ -d "$SDK/build-tools" ] || die "Android SDK not found. Set ANDROID_HOME, or install the command-line tools and run: sdkmanager \"build-tools;34.0.0\" \"platforms;android-34\""

BT_VER=$(ls "$SDK/build-tools" | sort -V | tail -n 1)
[ -n "$BT_VER" ] || die "no build-tools in $SDK/build-tools. Run: sdkmanager \"build-tools;34.0.0\""
BT="$SDK/build-tools/$BT_VER"
AJ=$(ls "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -n 1 || true)
[ -n "$AJ" ] || die "no android.jar in $SDK/platforms. Run: sdkmanager \"platforms;android-34\""

if [ -n "${JAVA_HOME:-}" ] && [ -x "$JAVA_HOME/bin/javac" ]; then
  JAVAC="$JAVA_HOME/bin/javac"; KEYTOOL="$JAVA_HOME/bin/keytool"
else
  JAVAC=$(command -v javac || true); KEYTOOL=$(command -v keytool || true)
fi
[ -n "$JAVAC" ] && [ -n "$KEYTOOL" ] || die "JDK not found (need JDK 17+). Install it (macOS: brew install --cask temurin; Linux: openjdk-17-jdk) or set JAVA_HOME."
for t in aapt2 d8 zipalign apksigner; do
  [ -x "$BT/$t" ] || die "$t missing in $BT (need build-tools 34+). Run: sdkmanager \"build-tools;34.0.0\""
done
command -v zip >/dev/null || die "zip not found. Install it with your package manager."

# --- settings --------------------------------------------------------------
if [ ! -f config.properties ]; then
  cp config.example.properties config.properties
  echo "Created config.properties: add your TMDB key and city, then build again"
fi

# prop KEY DEFAULT: last "KEY=value" line, quotes and backslashes removed.
prop() {
  local v
  v=$(grep -E "^[[:space:]]*$1[[:space:]]*=" config.properties | tail -n 1 || true)
  v=${v#*=}
  v=$(printf '%s' "$v" | tr -d '"\\' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')
  if [ -n "$v" ]; then printf '%s' "$v"; else printf '%s' "$2"; fi
}
is_number() { printf '%s' "$1" | grep -Eq '^-?[0-9]+(\.[0-9]+)?$'; }

APP_NAME=$(prop app_name WatchMatch)
CATALOG_NAME=$(prop catalog_name 'Watchme+')
SPARK_NAME=$(prop spark_name Spark)
TMDB_KEY=$(prop tmdb_key '')
TMDB_REGION=$(prop tmdb_region US)
YOUTUBE_KEY=$(prop youtube_key '')
YOUTUBE_CLIENT_ID=$(prop youtube_client_id '')
YOUTUBE_CLIENT_SECRET=$(prop youtube_client_secret '')
SUPABASE_URL=$(prop supabase_url '')
SUPABASE_ANON_KEY=$(prop supabase_anon_key '')
SITE_URL=$(prop site_url 'https://watch-me-plus.vercel.app')
LATITUDE=$(prop latitude 40.7128)
LONGITUDE=$(prop longitude -74.0060)
CITY=$(prop city '')
NAME=$(prop name '')
TEAMS=$(prop teams '')
LEAGUES=$(prop leagues 'uefa.champions,eng.1,esp.1')
LANGUAGE=$(prop language auto)
CURRENCY=$(prop currency USD)
TEMPERATURE=$(prop temperature auto)
[ "$(prop disable_assistant false)" = true ] && DISABLE_ASSISTANT=true || DISABLE_ASSISTANT=false
[ "$(prop show_crypto true)" = true ] && SHOW_CRYPTO=true || SHOW_CRYPTO=false

is_number "$LATITUDE" || die "latitude in config.properties must be a number like 40.7128 (got \"$LATITUDE\")"
is_number "$LONGITUDE" || die "longitude in config.properties must be a number like -74.0060 (got \"$LONGITUDE\")"

# --- generated Config.java -------------------------------------------------
rm -rf out
mkdir -p out/gen/io/watchmatch out/classes
{
  echo "package io.watchmatch;"
  echo
  echo "// Generated by build.sh from config.properties. Do not edit."
  echo "final class Config {"
  echo "    private Config() {}"
  for kv in "APP_NAME=$APP_NAME" "CATALOG_NAME=$CATALOG_NAME" "SPARK_NAME=$SPARK_NAME" \
            "TMDB_KEY=$TMDB_KEY" "TMDB_REGION=$TMDB_REGION" "YOUTUBE_KEY=$YOUTUBE_KEY" \
            "YOUTUBE_CLIENT_ID=$YOUTUBE_CLIENT_ID" "YOUTUBE_CLIENT_SECRET=$YOUTUBE_CLIENT_SECRET" \
            "SUPABASE_URL=$SUPABASE_URL" "SUPABASE_ANON_KEY=$SUPABASE_ANON_KEY" "SITE_URL=$SITE_URL" \
            "LATITUDE=$LATITUDE" "LONGITUDE=$LONGITUDE" "CITY=$CITY" "NAME=$NAME" "TEAMS=$TEAMS" \
            "LEAGUES=$LEAGUES" "LANGUAGE=$LANGUAGE" "CURRENCY=$CURRENCY" "TEMPERATURE=$TEMPERATURE"; do
    printf '    static final String %s = "%s";\n' "${kv%%=*}" "${kv#*=}"
  done
  echo "    static final boolean DISABLE_ASSISTANT = $DISABLE_ASSISTANT;"
  echo "    static final boolean SHOW_CRYPTO = $SHOW_CRYPTO;"
  echo "    static final long BUILD_TIME = $(date +%s)000L;"
  echo "}"
} > out/gen/io/watchmatch/Config.java

# --- resources (brand names into strings.xml) ------------------------------
cp -R app/res out/res
xml_sed() { # XML-escape, then escape for sed's replacement part
  printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g' -e "s/'/\\\\'/g" \
    -e 's/[\\&|]/\\&/g'
}
sed -e "s|{app}|$(xml_sed "$APP_NAME")|g" -e "s|{catalog}|$(xml_sed "$CATALOG_NAME")|g" \
  app/res/values/strings.xml > out/res/values/strings.xml

"$BT/aapt2" compile --dir out/res -o out/res.zip
"$BT/aapt2" link -o out/base.apk -I "$AJ" --manifest app/AndroidManifest.xml --java out/gen out/res.zip \
  --min-sdk-version 28 --target-sdk-version 33 -A app/assets -0 ttf

# --- code ------------------------------------------------------------------
find app/src out/gen -name '*.java' > out/sources.txt
"$JAVAC" -nowarn -Xlint:-options -source 8 -target 8 \
  -bootclasspath "$AJ:$BT/core-lambda-stubs.jar" -classpath "$AJ" -d out/classes @out/sources.txt 2> >(grep -v "^Note:" >&2)
find out/classes -name '*.class' > out/classfiles.txt
"$BT/d8" --release --min-api 28 --lib "$AJ" --output out @out/classfiles.txt
zip -qj out/base.apk out/classes.dex
"$BT/zipalign" -f -p 4 out/base.apk out/aligned.apk

# --- signing ---------------------------------------------------------------
if [ ! -f watchmatch.keystore ]; then
  "$KEYTOOL" -genkeypair -keystore watchmatch.keystore -alias watchmatch -keyalg RSA -keysize 2048 \
    -validity 20000 -storepass watchmatch -keypass watchmatch -dname "CN=WatchMatch" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks watchmatch.keystore --ks-pass pass:watchmatch --key-pass pass:watchmatch \
  --out WatchMatch.apk out/aligned.apk 2> >(grep -Ev "^(WARNING:|$)" >&2)
echo "Built WatchMatch.apk ($(du -h WatchMatch.apk | cut -f1)). Install: adb install -r WatchMatch.apk"
